    /** Tamil name to picture, for lines already saved in the history, which keep only the Tamil. */
    private val BY_TAMIL: Map<String, String> = run {
        val byTamil = HashMap<String, String>()
        for ((english, cue) in EMOJI) SoundLabelMap.tamilFor(english)?.let { byTamil[it] = cue }
        byTamil
    }

    /** The picture for an AudioSet class, or an empty string when it has none. */
    fun emojiFor(englishLabel: String): String = EMOJI[englishLabel].orEmpty()

    /** The picture for a Tamil sound name as the history stores it, or an empty string. */
    fun emojiForTamil(tamilLabel: String): String = BY_TAMIL[tamilLabel].orEmpty()

    /** The name with its picture in front: "🐕 நாய்". A name without a picture is returned as is. */
    fun withCue(englishLabel: String, tamilLabel: String): String {
        val cue = emojiFor(englishLabel)
        return if (cue.isEmpty()) tamilLabel else "$cue $tamilLabel"
    }

    /** Every class that has a picture, for the test that keeps pictures and names in step. */
    fun labels(): Set<String> = EMOJI.keys
