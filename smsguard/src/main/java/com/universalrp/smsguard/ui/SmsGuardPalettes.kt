data class GuardPalette(
    val id: Int,
    val nameEn: String,
    val nameTa: String,
    val bg: Color,
    val surface: Color,
    val card: Color,
    val accent: Color,
    val onAccent: Color,
    val textPrimary: Color,
    val textMuted: Color,
    val safeGreen: Color,
    val warnAmber: Color,
    val dangerRed: Color,
) {
    fun toColorScheme(): ColorScheme = darkColorScheme(
        primary = accent,
        onPrimary = onAccent,
        secondary = safeGreen,
        tertiary = warnAmber,
        background = bg,
        onBackground = textPrimary,
        surface = surface,
        onSurface = textPrimary,
        surfaceVariant = card,
        onSurfaceVariant = textMuted,
        error = dangerRed,
        onError = Color(0xFFFFFFFF),
    )
}

